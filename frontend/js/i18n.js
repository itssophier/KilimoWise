var currentLang = (function () {
  try { return localStorage.getItem('kilimowise_lang') || 'en'; } catch (e) { return 'en'; }
})();

function __(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key]) || TRANSLATIONS.en[key] || key;
}

function setLanguage(lang) {
  if (lang !== 'en' && lang !== 'sw') return;
  currentLang = lang;
  try { localStorage.setItem('kilimowise_lang', lang); } catch (e) { /* ignore */ }
  applyTranslations();
  document.dispatchEvent(new CustomEvent('kmw:lang', { detail: { lang: lang } }));
  var label = document.getElementById('langLabel');
  if (label) label.textContent = lang === 'en' ? 'EN / SW' : 'SW / EN';
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function (el) {
    var key = el.getAttribute('data-i18n');
    el.textContent = __(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-placeholder');
    el.placeholder = __(key);
  });
  document.querySelectorAll('[data-i18n-value]').forEach(function (el) {
    var key = el.getAttribute('data-i18n-value');
    el.value = __(key);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(function (el) {
    el.title = __(el.getAttribute('data-i18n-title'));
  });
  document.documentElement.lang = currentLang;
}

function toggleLanguage() {
  setLanguage(currentLang === 'en' ? 'sw' : 'en');
}

document.addEventListener('DOMContentLoaded', applyTranslations);
